const (
	// tlsDialName is the host name the client dials for every TLS fake; the dial hook connects it
	// to the fake's loopback address, so the name is never resolved.
	tlsDialName = "upstream.test"

	// tlsFailureText is the whole text of the error Do returns for a failed TLS handshake,
	// certificate verification included.
	tlsFailureText = "upstream TLS connection failed"
	// responseFailureText is the whole text of the error Do returns for another failure of an
	// attempt that obtained a connection.
	responseFailureText = "upstream response failed"

	// peerMarker is text only a fake peer supplies, in a certificate name or in an error its
	// configuration returns; an error text that contains it repeats the peer.
	peerMarker = "upstream-peer-marker-3d9a"
)

// testAuthority is a certificate authority generated by a test.
type testAuthority struct {
	cert *x509.Certificate
	key  *ecdsa.PrivateKey
}

func newTestKey(t *testing.T) *ecdsa.PrivateKey {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatalf("generate key: %v", err)
	}
	return key
}

func newSerial(t *testing.T) *big.Int {
	t.Helper()
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 62))
	if err != nil {
		t.Fatalf("generate serial number: %v", err)
	}
	return serial
}

// newTestAuthority returns a self-signed authority named subject, valid for an hour either side of
// now.
func newTestAuthority(t *testing.T, subject pkix.Name) testAuthority {
	t.Helper()
	key := newTestKey(t)
	now := time.Now()
	tmpl := &x509.Certificate{
		SerialNumber:          newSerial(t),
		Subject:               subject,
		NotBefore:             now.Add(-time.Hour),
		NotAfter:              now.Add(time.Hour),
		IsCA:                  true,
		BasicConstraintsValid: true,
		KeyUsage:              x509.KeyUsageCertSign | x509.KeyUsageDigitalSignature,
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	if err != nil {
		t.Fatalf("create authority %q: %v", subject.CommonName, err)
	}
	cert, err := x509.ParseCertificate(der)
	if err != nil {
		t.Fatalf("parse authority %q: %v", subject.CommonName, err)
	}
	return testAuthority{cert: cert, key: key}
}

// issueServerCert returns a server certificate for dnsNames signed by issuer, with extra sent after
// it in the chain the server presents.
func issueServerCert(t *testing.T, issuer testAuthority, dnsNames []string, extra ...*x509.Certificate) tls.Certificate {
	t.Helper()
	key := newTestKey(t)
	now := time.Now()
	tmpl := &x509.Certificate{
		SerialNumber: newSerial(t),
		Subject:      pkix.Name{CommonName: "upstream fake server"},
		DNSNames:     dnsNames,
		NotBefore:    now.Add(-time.Hour),
		NotAfter:     now.Add(time.Hour),
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, issuer.cert, &key.PublicKey, issuer.key)
	if err != nil {
		t.Fatalf("create server certificate: %v", err)
	}
	leaf, err := x509.ParseCertificate(der)
	if err != nil {
		t.Fatalf("parse server certificate: %v", err)
	}
	chain := [][]byte{der}
	for _, c := range extra {
		chain = append(chain, c.Raw)
	}
	return tls.Certificate{Certificate: chain, PrivateKey: key, Leaf: leaf}
}

// newTrustedServerCert returns a certificate for tlsDialName and roots that make the client trust
// it, so the certificate passes the standard verification.
func newTrustedServerCert(t *testing.T) (tls.Certificate, *x509.CertPool) {
	t.Helper()
	ca := newTestAuthority(t, pkix.Name{CommonName: "upstream test authority"})
	roots := x509.NewCertPool()
	roots.AddCert(ca.cert)
	return issueServerCert(t, ca, []string{tlsDialName}), roots
}

// requireVerifyErrorCarries fails t unless verifying cert the way the TLS client does fails with
// a message containing marker, so a test built on cert can see the peer's text leak.
func requireVerifyErrorCarries(t *testing.T, cert tls.Certificate, roots *x509.CertPool, marker string) {
	t.Helper()
	intermediates := x509.NewCertPool()
	for _, der := range cert.Certificate[1:] {
		c, err := x509.ParseCertificate(der)
		if err != nil {
			t.Fatalf("parse presented chain: %v", err)
		}
		intermediates.AddCert(c)
	}
	_, err := cert.Leaf.Verify(x509.VerifyOptions{Roots: roots, Intermediates: intermediates, DNSName: tlsDialName})
	if err == nil {
		t.Fatal("the fake's certificate verifies; the test needs one that fails")
	}
	if !strings.Contains(err.Error(), marker) {
		t.Fatalf("verifying the fake's certificate fails with %q, which lacks %q; the test could not see a leak", err, marker)
	}
}

// loopbackFake accepts loopback TCP connections and runs handle on each in its own goroutine. Its
// cleanup closes the listener and every accepted connection and waits for every goroutine.
type loopbackFake struct {
	ln       net.Listener
	handlers sync.WaitGroup

	mu    sync.Mutex
	conns []net.Conn
}

func startLoopbackFake(t *testing.T, handle func(net.Conn)) *loopbackFake {
	t.Helper()
	ln, err := new(net.ListenConfig).Listen(t.Context(), "tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatalf("listen: %v", err)
	}
	f := &loopbackFake{ln: ln}
	f.handlers.Go(func() {
		for {
			c, err := ln.Accept()
			if err != nil {
				return
			}
			f.mu.Lock()
			f.conns = append(f.conns, c)
			f.mu.Unlock()
			f.handlers.Go(func() {
				defer func() { _ = c.Close() }()
				handle(c)
			})
		}
	})
	t.Cleanup(func() {
		_ = ln.Close()
		f.mu.Lock()
		for _, c := range f.conns {
			_ = c.Close()
		}
		f.mu.Unlock()
		f.handlers.Wait()
	})
	return f
}

// dialFake connects every dial to the fake, whatever address the transport asks for, so the
// transport keeps the dialled host name for TLS verification.
func (f *loopbackFake) dialFake(ctx context.Context, network, _ string) (net.Conn, error) {
	var d net.Dialer
	return d.DialContext(ctx, network, f.ln.Addr().String())
}

// serveTLS runs a server handshake with cert on c; the client is expected to abort it.
func serveTLS(ctx context.Context, cert tls.Certificate) func(net.Conn) {
	return func(c net.Conn) {
		_ = tls.Server(c, &tls.Config{Certificates: []tls.Certificate{cert}}).HandshakeContext(ctx)
	}
}

// afterHandshake returns a connection handler that completes a server handshake with cert, reads
// one request through the TLS connection, calls send with the raw and the TLS connection, and then
// reads the raw connection until the client closes it.
func afterHandshake(t *testing.T, cert tls.Certificate, send func(raw net.Conn, tc *tls.Conn) error) func(net.Conn) {
	return func(raw net.Conn) {
		tc := tls.Server(raw, &tls.Config{Certificates: []tls.Certificate{cert}})
		if err := tc.HandshakeContext(t.Context()); err != nil {
			t.Errorf("fake server handshake: %v", err)
			return
		}
		req, err := http.ReadRequest(bufio.NewReader(tc))
		if err != nil {
			t.Errorf("fake server reading the request: %v", err)
			return
		}
		_, _ = io.Copy(io.Discard, req.Body)
		_ = req.Body.Close()
		if err := send(raw, tc); err != nil {
			t.Errorf("fake server sending its reply: %v", err)
			return
		}
		_, _ = io.Copy(io.Discard, raw)
	}
}

// doWithoutPanic calls client.Do and turns a panic in it into a failure of t, so that one test
// reports it and the other tests of the package still run.
func doWithoutPanic(t *testing.T, client *upstream.Client, req upstream.Request) (*upstream.Response, error) {
	t.Helper()
	defer func() {
		if r := recover(); r != nil {
			t.Fatalf("Do panicked: %v", r)
		}
	}()
	return client.Do(t.Context(), req)
}

// doOverTLS sends a request for https://upstream.test through a client configured with cfg whose
// dials reach fake, and returns the error of Do.
func doOverTLS(t *testing.T, fake *loopbackFake, cfg *tls.Config) error {
	t.Helper()
	client := upstream.NewClient(upstream.Options{DialContext: fake.dialFake, TLSConfig: cfg})
	defer func() { _ = client.Close() }()

	req := messagesRequest()
	req.BaseURL = "https://" + tlsDialName
	resp, err := doWithoutPanic(t, client, req)
	if resp != nil {
		_ = resp.Body.Close()
		t.Fatalf("Do returned status %d from a peer that must fail, want an error", resp.StatusCode)
	}
	if err == nil {
		t.Fatal("Do returned neither a response nor an error")
	}
	t.Logf("Do error: %v", err)
	return err
}

// requireTLSFailureText fails t unless err has exactly the fixed text of a TLS failure.
func requireTLSFailureText(t *testing.T, err error) {
	t.Helper()
	if got := err.Error(); got != tlsFailureText {
		t.Errorf("Do error text = %q, want exactly %q", got, tlsFailureText)
	}
}

func TestDoHidesPeerCertificateText(t *testing.T) {
	tests := map[string]struct {
		// fixture returns the certificate the fake presents, carrying peerMarker, and the roots
		// the client trusts.
		fixture func(t *testing.T) (tls.Certificate, *x509.CertPool)
		// check asserts that the verification error is still reachable through the unwrap chain.
		check func(t *testing.T, err error)
	}{
		"error: certificate names that do not match the dialled name": {
			fixture: func(t *testing.T) (tls.Certificate, *x509.CertPool) {
				ca := newTestAuthority(t, pkix.Name{CommonName: "upstream test authority"})
				roots := x509.NewCertPool()
				roots.AddCert(ca.cert)
				return issueServerCert(t, ca, []string{peerMarker + ".example", "www." + peerMarker + ".example"}), roots
			},
			check: func(t *testing.T, err error) {
				if _, ok := errors.AsType[x509.HostnameError](err); !ok {
					t.Errorf("Do against a certificate for other names = %v, want x509.HostnameError in the unwrap chain", err)
				}
			},
		},
		"error: a certificate signed by an authority the client does not trust": {
			fixture: func(t *testing.T) (tls.Certificate, *x509.CertPool) {
				trusted := newTestAuthority(t, pkix.Name{CommonName: "upstream test authority"})
				roots := x509.NewCertPool()
				roots.AddCert(trusted.cert)
				// The issuer is unknown to the client. The peer also presents a certificate with the
				// issuer's name but another key; the verifier tries it as the issuer, and its error
				// text quotes the name of that peer-supplied certificate.
				issuerName := pkix.Name{CommonName: peerMarker + " issuing authority"}
				issuer := newTestAuthority(t, issuerName)
				impostor := newTestAuthority(t, issuerName)
				return issueServerCert(t, issuer, []string{tlsDialName}, impostor.cert), roots
			},
			check: func(t *testing.T, err error) {
				if _, ok := errors.AsType[x509.UnknownAuthorityError](err); !ok {
					t.Errorf("Do against a certificate from an untrusted authority = %v, want x509.UnknownAuthorityError in the unwrap chain", err)
				}
			},
		},
	}

	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			cert, roots := tt.fixture(t)
			requireVerifyErrorCarries(t, cert, roots, peerMarker)

			fake := startLoopbackFake(t, serveTLS(t.Context(), cert))
			err := doOverTLS(t, fake, &tls.Config{RootCAs: roots})
			requireTLSFailureText(t, err)
			if _, ok := errors.AsType[*tls.CertificateVerificationError](err); !ok {
				t.Errorf("Do error = %v, want *tls.CertificateVerificationError in the unwrap chain", err)
			}
			tt.check(t, err)
		})
	}
}

// hookDetailError is an error whose field holds a value of any type. Two of them compare without
// a panic only while the field holds comparable values; holding a slice, == panics.
type hookDetailError struct {
	detail any
}

func (e hookDetailError) Error() string {
	return fmt.Sprintf("verification hook rejected the peer: %v", e.detail)
}

// hookListError is a slice, so no two of its values can be compared.
type hookListError []string

func (e hookListError) Error() string {
	return "verification hook rejected the peer: " + strings.Join(e, ", ")
}

// hookCanceledError wraps context.Canceled, although no context ended.
type hookCanceledError struct {
	detail string
}

func (e *hookCanceledError) Error() string {
	return "verification hook gave up on " + e.detail + ": " + context.Canceled.Error()
}

func (e *hookCanceledError) Unwrap() error {
	return context.Canceled
}

func TestDoHidesVerificationHookErrors(t *testing.T) {
	canceledErr := &hookCanceledError{detail: peerMarker}

	tests := map[string]struct {
		// hookErr is what the client's VerifyConnection hook returns for a certificate that passed
		// the standard verification.
		hookErr error
		// check asserts that the hook's own error is still reachable through the unwrap chain.
		check func(t *testing.T, err error)
	}{
		"error: a hook error whose interface field holds a slice": {
			hookErr: hookDetailError{detail: []string{peerMarker}},
			check: func(t *testing.T, err error) {
				got, ok := errors.AsType[hookDetailError](err)
				if !ok {
					t.Fatalf("Do error = %v, want the hook's hookDetailError in the unwrap chain", err)
				}
				if diff := gocmp.Diff(any([]string{peerMarker}), got.detail); diff != "" {
					t.Errorf("hookDetailError in the unwrap chain holds another value (-want +got):\n%s", diff)
				}
			},
		},
		"error: a hook error whose values cannot be compared": {
			hookErr: hookListError{peerMarker},
			check: func(t *testing.T, err error) {
				got, ok := errors.AsType[hookListError](err)
				if !ok {
					t.Fatalf("Do error = %v, want the hook's hookListError in the unwrap chain", err)
				}
				if diff := gocmp.Diff(hookListError{peerMarker}, got); diff != "" {
					t.Errorf("hookListError in the unwrap chain differs (-want +got):\n%s", diff)
				}
			},
		},
		"error: a hook error wrapping context.Canceled while the caller's context is alive": {
			hookErr: canceledErr,
			check: func(t *testing.T, err error) {
				if t.Context().Err() != nil {
					t.Fatal("the caller's context ended; the case needs it alive")
				}
				got, ok := errors.AsType[*hookCanceledError](err)
				if !ok || got != canceledErr {
					t.Errorf("Do error = %v, want the hook's *hookCanceledError in the unwrap chain", err)
				}
				if !errors.Is(err, context.Canceled) {
					t.Errorf("Do error = %v, want context.Canceled still reachable through the unwrap chain", err)
				}
			},
		},
	}

	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			cert, roots := newTrustedServerCert(t)
			fake := startLoopbackFake(t, serveTLS(t.Context(), cert))
			err := doOverTLS(t, fake, &tls.Config{
				RootCAs:          roots,
				VerifyConnection: func(tls.ConnectionState) error { return tt.hookErr },
			})
			requireTLSFailureText(t, err)
			tt.check(t, err)
		})
	}
}

func TestDoHidesBrokenTLSRecords(t *testing.T) {
	tests := map[string]struct {
		// handle returns the fake's handler for each accepted connection.
		handle func(t *testing.T, cert tls.Certificate) func(net.Conn)
		// wantTexts lists the accepted texts of the error Do returns.
		wantTexts []string
		// check, when set, asserts the unwrap chain.
		check func(t *testing.T, err error)
	}{
		"error: a peer that answers the TLS handshake in plain text": {
			handle: func(*testing.T, tls.Certificate) func(net.Conn) {
				return func(c net.Conn) {
					replyAfterFirstByte(c, "HTTP/1.1 400 "+wireMarker+"\r\nContent-Length: 0\r\n\r\n")
				}
			},
			wantTexts: []string{tlsFailureText},
			check: func(t *testing.T, err error) {
				if _, ok := errors.AsType[tls.RecordHeaderError](err); !ok {
					t.Errorf("Do against a plain-text reply to a TLS handshake = %v, want tls.RecordHeaderError in the unwrap chain", err)
				}
			},
		},
		"error: a response head sent in plain text after a completed handshake": {
			handle: func(t *testing.T, cert tls.Certificate) func(net.Conn) {
				return afterHandshake(t, cert, func(raw net.Conn, _ *tls.Conn) error {
					_, err := io.WriteString(raw, "HTTP/1.1 200 "+wireMarker+"\r\nContent-Length: 0\r\n\r\n")
					return err
				})
			},
			// The plain text reaches the client as a record header it rejects, an exported TLS
			// error type, so Do reports the TLS failure rather than the generic response failure.
			wantTexts: []string{tlsFailureText},
			check: func(t *testing.T, err error) {
				if _, ok := errors.AsType[tls.RecordHeaderError](err); !ok {
					t.Errorf("Do against a plain-text response head after a completed handshake = %v, want tls.RecordHeaderError in the unwrap chain", err)
				}
			},
		},
		// The decryption failure is reported by an alert of a type the TLS package does not
		// export, so either fixed sentence is accepted here.
		"error: a corrupted record inside the response head after a completed handshake": {
			handle: func(t *testing.T, cert tls.Certificate) func(net.Conn) {
				return afterHandshake(t, cert, func(raw net.Conn, tc *tls.Conn) error {
					// The status line and one header line arrive intact, so the client is
					// reading the response head when the next record fails to decrypt.
					if _, err := io.WriteString(tc, "HTTP/1.1 200 OK\r\nX-Upstream-Marker: "+wireMarker+"\r\n"); err != nil {
						return err
					}
					// An application data record of 32 zero bytes, which no key decrypts.
					record := append([]byte{0x17, 0x03, 0x03, 0x00, 0x20}, make([]byte, 0x20)...)
					_, err := raw.Write(record)
					return err
				})
			},
			wantTexts: []string{tlsFailureText, responseFailureText},
		},
	}

	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			cert, roots := newTrustedServerCert(t)
			fake := startLoopbackFake(t, tt.handle(t, cert))
			err := doOverTLS(t, fake, &tls.Config{RootCAs: roots})
			if got := err.Error(); !slices.Contains(tt.wantTexts, got) {
				t.Errorf("Do error text = %q, want exactly one of %q", got, tt.wantTexts)
			}
			if tt.check != nil {
				tt.check(t, err)
			}
		})
	}
}

func TestDoKeepsDialErrors(t *testing.T) {
	tests := map[string]struct {
		scheme string
		// dialErr is what Options.DialContext returns for every dial.
		dialErr error
	}{
		"error: a refused dial to an http upstream keeps the dial error and its text": {
			scheme:  "http",
			dialErr: newRefusedDial(),
		},
		"error: a refused dial to an https upstream keeps the dial error and its text": {
			scheme:  "https",
			dialErr: newRefusedDial(),
		},
		"error: a dial failing with tls.RecordHeaderError keeps its error and its text": {
			scheme:  "https",
			dialErr: tls.RecordHeaderError{Msg: "dialer saw a record header"},
		},
		"error: a dial failing with tls.AlertError keeps its error and its text": {
			scheme:  "https",
			dialErr: tls.AlertError(80),
		},
		"error: a dial failing with *tls.CertificateVerificationError keeps its error and its text": {
			scheme:  "https",
			dialErr: &tls.CertificateVerificationError{Err: errors.New("dialer rejected the certificate")},
		},
	}

	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			client := upstream.NewClient(upstream.Options{
				DialContext: func(context.Context, string, string) (net.Conn, error) { return nil, tt.dialErr },
			})
			defer func() { _ = client.Close() }()

			req := messagesRequest()
			req.BaseURL = tt.scheme + "://" + tlsDialName
			resp, err := doWithoutPanic(t, client, req)
			if resp != nil {
				_ = resp.Body.Close()
				t.Fatalf("Do returned status %d, want an error", resp.StatusCode)
			}
			if err == nil {
				t.Fatal("Do returned neither a response nor an error")
			}
			if !errors.Is(err, tt.dialErr) {
				t.Errorf("Do error = %v, want the dial's error %v in the unwrap chain", err, tt.dialErr)
			}
			if got, want := err.Error(), tt.dialErr.Error(); got != want {
				t.Errorf("Do error text = %q, want the dial error's text %q", got, want)
			}
		})
	}
}

// earlierFailureDial connects its first dial to a fake and fails every later dial with the error
// set by refuseWith.
type earlierFailureDial struct {
	fake *loopbackFake

	mu      sync.Mutex
	dialed  bool
	refusal error
}

func (d *earlierFailureDial) refuseWith(err error) {
	d.mu.Lock()
	defer d.mu.Unlock()
	d.refusal = err
}

func (d *earlierFailureDial) DialContext(ctx context.Context, network, addr string) (net.Conn, error) {
	d.mu.Lock()
	first := !d.dialed
	d.dialed = true
	refusal := d.refusal
	d.mu.Unlock()
	if first {
		return d.fake.dialFake(ctx, network, addr)
	}
	if refusal == nil {
		return nil, errors.New("a later dial ran before the test set its error")
	}
	return nil, refusal
}

func TestDoKeepsDialErrorWrappingEarlierTLSFailure(t *testing.T) {
	tests := map[string]struct {
		// wrap returns the error the custom dial reports, wrapping earlier, the error Do returned
		// for a failed TLS exchange of the same client.
		wrap func(earlier error) error
	}{
		"error: a custom dial wrapping the TLS error of an earlier exchange keeps its error and its text": {
			wrap: func(earlier error) error {
				return fmt.Errorf("dialer refuses after the earlier failure: %w", earlier)
			},
		},
	}

	for name, tt := range tests {
		t.Run(name, func(t *testing.T) {
			cert, _ := newTrustedServerCert(t)
			// The client trusts only another authority, so the first exchange fails verification.
			stranger := newTestAuthority(t, pkix.Name{CommonName: "upstream authority the fake did not use"})
			roots := x509.NewCertPool()
			roots.AddCert(stranger.cert)

			dial := &earlierFailureDial{fake: startLoopbackFake(t, serveTLS(t.Context(), cert))}
			client := upstream.NewClient(upstream.Options{DialContext: dial.DialContext, TLSConfig: &tls.Config{RootCAs: roots}})
			defer func() { _ = client.Close() }()

			req := messagesRequest()
			req.BaseURL = "https://" + tlsDialName
			resp, earlier := doWithoutPanic(t, client, req)
			if resp != nil {
				_ = resp.Body.Close()
				t.Fatalf("first Do returned status %d from a certificate the client does not trust, want an error", resp.StatusCode)
			}
			if earlier == nil {
				t.Fatal("first Do returned neither a response nor an error")
			}
			// Preconditions: the wrapped error is the client's own fixed TLS error.
			if got := earlier.Error(); got != tlsFailureText {
				t.Fatalf("first Do error text = %q, want exactly %q; the case needs the client's TLS error", got, tlsFailureText)
			}
			if _, ok := errors.AsType[*tls.CertificateVerificationError](earlier); !ok {
				t.Fatalf("first Do error = %v, want *tls.CertificateVerificationError in the unwrap chain", earlier)
			}

			dialErr := tt.wrap(earlier)
			dial.refuseWith(dialErr)
			resp, err := doWithoutPanic(t, client, req)
			if resp != nil {
				_ = resp.Body.Close()
				t.Fatalf("second Do returned status %d, want the dial's error", resp.StatusCode)
			}
			if err == nil {
				t.Fatal("second Do returned neither a response nor an error")
			}
			t.Logf("second Do error: %v", err)
			if !errors.Is(err, dialErr) {
				t.Errorf("second Do error = %v, want the dial's error %v in the unwrap chain", err, dialErr)
			}
			if got, want := err.Error(), dialErr.Error(); got != want {
				t.Errorf("second Do error text = %q, want the dial error's text %q", got, want)
			}
		})
	}
}

// newRefusedDial returns the error net.Dialer reports for a refused TCP connect.
func newRefusedDial() error {
	return &net.OpError{
		Op:   "dial",
		Net:  "tcp",
		Addr: &net.TCPAddr{IP: net.IPv4(127, 0, 0, 1), Port: 9},
		Err:  os.NewSyscallError("connect", syscall.ECONNREFUSED),
	}
}
